"""Build vendor/moon-maps.js from NASA's CGI Moon Kit.

SI disclosure: this file was written with an AI coding tool (Claude Code,
Anthropic) during the 2026 NASA Space Apps Challenge, Nov 14-15, 2026,
directed and reviewed by team Ksig UNT. See SI_USE.md.

Source: NASA Scientific Visualization Studio, CGI Moon Kit
        https://svs.gsfc.nasa.gov/4720/
  - Colour: LROC WAC natural-colour mosaic (Lunar Reconnaissance Orbiter Camera,
    Arizona State University), equirectangular, centred on 0 deg longitude.
  - Elevation: LOLA gridded elevation at 4 pixels per degree (Lunar Orbiter
    Laser Altimeter), unsigned 16-bit, half-metres above a 1727.4 km radius.

The page opens straight from disk, and browsers refuse to load image files
into WebGL from file:// addresses. So the two maps are stored inside a script
as data URIs, which every browser accepts.

Usage:  python tools/build_moon_maps.py
Needs Pillow and NumPy. Downloads about 15 MB into .cache/ the first time.
"""

import base64
import io
import os
import urllib.request

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, ".cache", "nasa-svs-4720")
OUT = os.path.join(ROOT, "vendor", "moon-maps.js")
BASE = "https://svs.gsfc.nasa.gov/vis/a000000/a004700/a004720/"
COLOR_FILE = "lroc_color_poles_4k.tif"
ELEV_FILE = "ldem_4_uint.tif"
COLOR_WIDTH = 4096
JPEG_QUALITY = 82
MOON_RADIUS_KM = 1737.4
SLOPE_MAX = 0.5  # slopes are stored from -0.5 to +0.5 (about 27 degrees)

Image.MAX_IMAGE_PIXELS = 200_000_000


def fetch(name):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, name)
    if not os.path.exists(path):
        print("downloading", name)
        urllib.request.urlretrieve(BASE + name, path)
    return path


def data_uri(mime, raw):
    return "data:%s;base64,%s" % (mime, base64.b64encode(raw).decode("ascii"))


def main():
    color = Image.open(fetch(COLOR_FILE)).convert("RGB")
    if color.width != COLOR_WIDTH:
        color = color.resize((COLOR_WIDTH, COLOR_WIDTH // 2), Image.LANCZOS)
    buf = io.BytesIO()
    color.save(buf, "JPEG", quality=JPEG_QUALITY, optimize=True)
    color_bytes = buf.getvalue()

    elev = np.array(Image.open(fetch(ELEV_FILE))).astype(np.float64)
    km = elev / 2000.0 - 10.0  # half-metres above 1727.4 km -> km above 1737.4 km
    lo, hi = float(km.min()), float(km.max())
    scaled = np.round((km - lo) / (hi - lo) * 255.0).astype(np.uint8)

    # Ground slope toward east and toward north, as rise over run. The page
    # tilts the surface by these when it shades the globe. Row 0 is the north
    # edge. Near the poles a pixel covers very little ground east to west, so
    # the east slope is measured across more pixels there to keep the ground
    # distance about the same at every latitude.
    rows, cols = km.shape
    lat = np.radians(90.0 - (np.arange(rows) + 0.5) * 180.0 / rows)
    row_km = MOON_RADIUS_KM * np.pi / rows
    north = np.empty_like(km)
    north[1:-1] = (km[:-2] - km[2:]) / (2.0 * row_km)
    north[0], north[-1] = north[1], north[-2]
    east = np.empty_like(km)
    for i in range(rows):
        k = int(min(max(round(1.0 / np.cos(lat[i])), 1), cols // 8))
        run = MOON_RADIUS_KM * np.cos(lat[i]) * (2.0 * np.pi / cols) * k
        east[i] = (np.roll(km[i], -k) - np.roll(km[i], k)) / (2.0 * run)
    clipped = float(np.mean((np.abs(east) > SLOPE_MAX) | (np.abs(north) > SLOPE_MAX)))

    def encode(slope):
        return np.round(np.clip(0.5 + slope / (2.0 * SLOPE_MAX), 0.0, 1.0) * 255.0).astype(np.uint8)

    relief = np.dstack([encode(east), encode(north), scaled])
    buf = io.BytesIO()
    Image.fromarray(relief, mode="RGB").save(buf, "PNG", optimize=True)
    elev_bytes = buf.getvalue()

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("/*\n")
        f.write(" * moon-maps.js  (generated by tools/build_moon_maps.py; do not edit by hand)\n")
        f.write(" * Data: NASA Scientific Visualization Studio, CGI Moon Kit, https://svs.gsfc.nasa.gov/4720/\n")
        f.write(" * Colour: LROC WAC mosaic (NASA/GSFC/Arizona State University). Elevation: LOLA (NASA/GSFC).\n")
        f.write(" * Both maps are equirectangular and centred on 0 degrees longitude.\n")
        f.write(" */\n")
        f.write("window.MoonMaps = {\n")
        f.write('  credit: "NASA Scientific Visualization Studio, CGI Moon Kit (LROC WAC colour, LOLA elevation)",\n')
        f.write('  creditUrl: "https://svs.gsfc.nasa.gov/4720/",\n')
        f.write("  colorSize: [%d, %d],\n" % color.size)
        f.write("  elevationSize: [%d, %d],\n" % (scaled.shape[1], scaled.shape[0]))
        f.write("  elevationRangeKm: [%.3f, %.3f],\n" % (lo, hi))
        f.write("  slopeMax: %.2f,\n" % SLOPE_MAX)
        f.write('  color: "%s",\n' % data_uri("image/jpeg", color_bytes))
        f.write("  /* red: slope toward east, green: slope toward north, blue: height */\n")
        f.write('  relief: "%s"\n' % data_uri("image/png", elev_bytes))
        f.write("};\n")

    print("colour %dx%d, %.0f KB JPEG" % (color.width, color.height, len(color_bytes) / 1024))
    print("relief %dx%d, %.0f KB PNG, range %.2f to %.2f km, %.3f%% of slopes clipped at %.2f" % (
        scaled.shape[1], scaled.shape[0], len(elev_bytes) / 1024, lo, hi, clipped * 100, SLOPE_MAX))
    print("wrote %s, %.0f KB" % (OUT, os.path.getsize(OUT) / 1024))


if __name__ == "__main__":
    main()
